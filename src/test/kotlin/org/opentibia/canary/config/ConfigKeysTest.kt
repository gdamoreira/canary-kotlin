package org.opentibia.canary.config

import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test

class ConfigKeysTest {

    @Test
    fun `registers every loadable Canary config key exactly once`() {
        assertThat(ConfigKeys.all).hasSize(360)
        assertThat(ConfigKeys.all.map { it.name }).doesNotHaveDuplicates()
        assertThat(ConfigKeys.all.map { it.name }).containsExactlyElementsOf(expectedKeyTypes.keys)
    }

    @Test
    fun `every registered key has the exact type from configmanager`() {
        assertThat(ConfigKeys.all.associate { it.name to it.type }).isEqualTo(expectedKeyTypes)
    }

    @Test
    fun `omits ONE_PLAYER_ON_ACCOUNT which configmanager never loads`() {
        assertThat(expectedKeyTypes).doesNotContainKey("ONE_PLAYER_ON_ACCOUNT")
        assertThat(ConfigKeys.byName("ONE_PLAYER_ON_ACCOUNT")).isNull()
    }

    @Test
    fun `defaults match the Canary configmanager values across every type`() {
        assertThat(ConfigKeys.defaults()).containsAllEntriesOf(sampledDefaults)
    }

    @Test
    fun `declared type matches the runtime type of every default`() {
        ConfigKeys.all.forEach { key ->
            val matches = when (key.type) {
                ConfigKeyType.BOOLEAN -> key.defaultValue is Boolean
                ConfigKeyType.INTEGER -> key.defaultValue is Int
                ConfigKeyType.FLOAT -> key.defaultValue is Float
                ConfigKeyType.STRING -> key.defaultValue is String
            }
            assertThat(matches)
                .withFailMessage("default %s is not a %s for key %s", key.defaultValue, key.type, key.name)
                .isTrue()
        }
    }

    @Test
    fun `lua identifiers match the configmanager globals`() {
        assertThat(ConfigKeys.all.associate { it.name to it.luaIdentifier })
            .containsAllEntriesOf(sampledIdentifiers)
    }

    @Test
    fun `byName looks up keys and returns null for unknown names`() {
        assertThat(ConfigKeys.byName("GAME_PORT"))
            .isEqualTo(ConfigKey("GAME_PORT", ConfigKeyType.INTEGER, 7172, "gameProtocolPort"))
        assertThat(ConfigKeys.byName("gameProtocolPort")).isNull()
        assertThat(ConfigKeys.byName("")).isNull()
    }

    @Test
    fun `defaults returns a value for every registered key`() {
        assertThat(ConfigKeys.defaults()).hasSize(ConfigKeys.all.size)
        assertThat(ConfigKeys.defaults().keys).containsExactlyElementsOf(ConfigKeys.all.map { it.name })
    }

