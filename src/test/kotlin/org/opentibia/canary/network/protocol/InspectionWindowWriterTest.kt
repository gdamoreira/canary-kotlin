package org.opentibia.canary.network.protocol

import io.netty.buffer.ByteBuf
import io.netty.buffer.Unpooled
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import org.opentibia.canary.items.Item
import org.opentibia.canary.items.ItemType
import org.opentibia.canary.items.Items
import org.opentibia.canary.items.SLOTP_RING

class InspectionWindowWriterTest {

    private fun ByteBuf.toByteArray(): ByteArray {
        val bytes = ByteArray(readableBytes())
        readBytes(bytes)
        return bytes
    }

    private fun bytes(vararg values: Int): ByteArray = ByteArray(values.size) { values[it].toByte() }

    @Test
    fun `writes an item inspection 0x76 from an item id and the plural descriptions`() {
        val items = Items().apply {
            register(ItemType(id = 2160, name = "gold coin", isStackable = true, weight = 0.1))
        }
        val out = Unpooled.buffer()

        InspectionWindowWriter.writeItemInspection(
            out,
            playerId = 5L,
            cyclopedia = false,
            itemId = 2160,
            itemCount = 1,
            items = items,
        )

        assertThat(out.toByteArray()).containsExactly(
            *bytes(
                0x76, 0x00, 0x00,
                0x05, 0x00, 0x00, 0x00,
                0x01,
                0x09, 0x00, 0x67, 0x6F, 0x6C, 0x64, 0x20, 0x63, 0x6F, 0x69, 0x6E,
                0x70, 0x08, 0x01,
                0x00,
                0x03,
                0x06, 0x00, 0x57, 0x65, 0x69, 0x67, 0x68, 0x74,
                0x07, 0x00, 0x30, 0x2E, 0x31, 0x30, 0x20, 0x6F, 0x7A,
                0x13, 0x00, 0x54, 0x72, 0x61, 0x64, 0x65, 0x61, 0x62, 0x6C, 0x65,
                0x20, 0x49, 0x6E, 0x20, 0x4D, 0x61, 0x72, 0x6B, 0x65, 0x74,
                0x03, 0x00, 0x79, 0x65, 0x73,
                0x0D, 0x00, 0x42, 0x6F, 0x64, 0x79, 0x20, 0x50, 0x6F, 0x73, 0x69, 0x74, 0x69, 0x6F, 0x6E,
                0x0B, 0x00, 0x77, 0x65, 0x61, 0x70, 0x6F, 0x6E, 0x20, 0x68, 0x61, 0x6E, 0x64,
            )
        )
    }

    @Test
    fun `writes the cyclopedia item inspection from an item instance`() {
        val items = Items().apply {
            register(ItemType(id = 200, name = "ring", slotPosition = SLOTP_RING, description = "A plain ring."))
        }
        val out = Unpooled.buffer()

        InspectionWindowWriter.writeItemInspection(
            out,
            playerId = 1L,
            cyclopedia = true,
            itemId = 200,
            itemCount = 0,
            item = Item(id = 200, type = items.get(200)),
            items = items,
        )

        assertThat(out.toByteArray()).containsExactly(
            *bytes(
                0x76, 0x00, 0x01,
                0x01, 0x00, 0x00, 0x00,
                0x01,
                0x04, 0x00, 0x72, 0x69, 0x6E, 0x67,
                0xC8, 0x00,
                0x00,
                0x03,
                0x0B, 0x00, 0x44, 0x65, 0x73, 0x63, 0x72, 0x69, 0x70, 0x74, 0x69, 0x6F, 0x6E,
                0x0D, 0x00, 0x41, 0x20, 0x70, 0x6C, 0x61, 0x69, 0x6E, 0x20, 0x72, 0x69, 0x6E, 0x67, 0x2E,
                0x09, 0x00, 0x54, 0x72, 0x61, 0x64, 0x65, 0x61, 0x62, 0x6C, 0x65,
                0x03, 0x00, 0x79, 0x65, 0x73,
                0x0D, 0x00, 0x42, 0x6F, 0x64, 0x79, 0x20, 0x50, 0x6F, 0x73, 0x69, 0x74, 0x69, 0x6F, 0x6E,
                0x06, 0x00, 0x66, 0x69, 0x6E, 0x67, 0x65, 0x72,
            )
        )
    }
}
