/**
 * `CombatType_t` (`src/creatures/creatures_definitions.hpp:833-853`).
 *
 * `combatTypeToIndex`/`indexToCombatType` are identity over these values
 * (`src/utils/tools.cpp:1215-1243`), so [value] doubles as the array index.
 */
enum class CombatType(val value: Int) {
    COMBAT_PHYSICALDAMAGE(0),
    COMBAT_FIREDAMAGE(1),
    COMBAT_EARTHDAMAGE(2),
    COMBAT_ENERGYDAMAGE(3),
    COMBAT_UNDEFINEDDAMAGE(4),
    COMBAT_LIFEDRAIN(5),
    COMBAT_MANADRAIN(6),
    COMBAT_HEALING(7),
    COMBAT_DROWNDAMAGE(8),
    COMBAT_ICEDAMAGE(9),
    COMBAT_HOLYDAMAGE(10),
    COMBAT_DEATHDAMAGE(11),
    COMBAT_AGONYDAMAGE(12),
    COMBAT_NEUTRALDAMAGE(13),

    COMBAT_COUNT(14),
    COMBAT_NONE(255);

    /** `Combat::ConditionToDamageType` (`src/creatures/combat/combat.cpp:245-276`). */
    companion object {
        fun conditionToDamageType(type: ConditionType): CombatType = when (type) {
            ConditionType.CONDITION_FIRE -> COMBAT_FIREDAMAGE
            ConditionType.CONDITION_ENERGY -> COMBAT_ENERGYDAMAGE
            ConditionType.CONDITION_BLEEDING -> COMBAT_PHYSICALDAMAGE
            ConditionType.CONDITION_DROWN -> COMBAT_DROWNDAMAGE
            ConditionType.CONDITION_POISON -> COMBAT_EARTHDAMAGE
            ConditionType.CONDITION_FREEZING -> COMBAT_ICEDAMAGE
            ConditionType.CONDITION_DAZZLED -> COMBAT_HOLYDAMAGE
            ConditionType.CONDITION_CURSED -> COMBAT_DEATHDAMAGE
            else -> COMBAT_NONE
        }
    }
}

