package org.opentibia.canary.config

/**
 * Value type of a Canary configuration key.
 *
 * Mirrors the four `ConfigManager::load*Config` families in Canary
 * `src/config/configmanager.cpp` and the `ConfigValue` variant in
 * `src/config/configmanager.hpp`.
 */
enum class ConfigKeyType {
    BOOLEAN,
    INTEGER,
    FLOAT,
    STRING,
}

/**
 * A single Canary configuration key.
 *
 * [name] is the enum-derived key name (`magic_enum::enum_name(ConfigKey_t::...)` in
 * `src/config/config_enums.hpp`), [luaIdentifier] is the `config.lua` global read by
 * `ConfigManager::load`, and [defaultValue] is the exact default passed to the matching
 * `load*Config` overload.
 */
data class ConfigKey(
    val name: String,
    val type: ConfigKeyType,
    val defaultValue: Any,
    val luaIdentifier: String,
) {
    init {
        require(defaultValue.matches(type)) {
            "Default value '$defaultValue' does not match $type for config key $name"
        }
    }

    private companion object {
        fun Any.matches(type: ConfigKeyType): Boolean = when (type) {
            ConfigKeyType.BOOLEAN -> this is Boolean
            ConfigKeyType.INTEGER -> this is Int
            ConfigKeyType.FLOAT -> this is Float
            ConfigKeyType.STRING -> this is String
        }
    }
}

